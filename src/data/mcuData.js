// Grouping helper
export const getGroupedTimeline = () => {
  const groups = {};
  mcuTimeline.forEach(item => {
    if (!groups[item.groupName]) {
      groups[item.groupName] = [];
    }
    groups[item.groupName].push(item);
  });
  return Object.keys(groups).map(key => ({
    name: key,
    items: groups[key]
  }));
};

